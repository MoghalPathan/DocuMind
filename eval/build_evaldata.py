"""Builds web/src/site/evalData.js from the real result files and the grade files.

No number is typed by hand: every row comes from results_<doc>_groq.json (what the system did)
and grades_<doc>_groq.json (the grade). Usage:  python build_evaldata.py RESULTS_DIR GRADES_DIR OUT_FILE
"""
import json
import re
import sys
from pathlib import Path

results_dir, grades_dir, out_file = (Path(p) for p in sys.argv[1:4])

DOCS = [
    ("lab", "Lab manual", "Deep Learning lab manual", True),
    ("yolo", "YOLO paper", "ECP-YOLO11n insulator defect detection paper", False),
    ("uav", "UAV paper", "UAV firmware trust paper", False),
]

# Short notes for the rows that are not fully correct (plain words, for the Results page).
