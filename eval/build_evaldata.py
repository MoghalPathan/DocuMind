def clean(text, limit):
    """The model's answer as plain text: no markdown marks, tables flattened, long answers cut."""
    text = text.replace("\r", "").replace("‑", "-").replace("‐", "-").replace(" ", " ")
    text = text.replace("\\(", "").replace("\\)", "").replace("\\[", "").replace("\\]", "")
    lines = []
    for ln in text.split("\n"):
        s = ln.strip()
        if not s:
            continue
        if re.fullmatch(r"\|?[\s\-:|]+\|?", s):  # table separator row
            continue
        if s.startswith("|"):
            cells = [c.strip() for c in s.strip("|").split("|")]
            s = " / ".join(c for c in cells if c)
        s = s.replace("**", "").replace("`", "")
        s = re.sub(r"[ \t]+", " ", s)
        lines.append(s)
    out = "\n".join(lines)
    if len(out) > limit:
        cut = out[:limit]
        at = max(cut.rfind(" "), cut.rfind("\n"))
        out = cut[: at if at > limit * 0.6 else limit].rstrip(" ,;:/-") + " ..."
    return out


rows = []
for key, _, _, _ in DOCS:
    res = json.loads((results_dir / f"results_{key}_groq.json").read_text(encoding="utf-8"))
    gr = json.loads((grades_dir / f"grades_{key}_groq.json").read_text(encoding="utf-8"))["grades"]
    assert [r["id"] for r in res] == [g["id"] for g in gr], key
    label = {"lab": "Lab", "yolo": "YOLO", "uav": "UAV"}[key]
    for r, g in zip(res, gr):
        grade = g["grade"]
        limit = 420 if grade in ("c", "r") else 750
        row = {
            "id": f"{label} {r['id'].upper()}",
            "doc": key,
            "answerable": r["answerable"],
            "q": r["question"],
            "expected": r["ground_truth"],
            "said": clean(r["answer"], limit),
            "grade": grade,
            "found": bool(r["evidence_hit"]),
        }
        note = NOTES.get((key, r["id"]))
        if grade in ("p", "w"):
            assert note, (key, r["id"], "needs a note")
            row["note"] = note
        else:
            assert not note, (key, r["id"], "note on a good row")
        rows.append(row)

docs_js = [{"key": k, "name": n, "full": f, "tuned": t} for k, n, f, t in DOCS]
header = (
    "// Graded results of the real evaluation run: Groq gpt-oss-20b, one fixed model, no backup model, each question asked once.\n"
    "// grade: c = correct, p = partly correct, w = wrong, r = correctly refused (\"I don't know\").\n"
    "// found: the text that holds the answer was in the passages given to the model.\n"
    "// tuned: the questions of this document were used while building DocuMind, so it is not a fair test.\n"
    "// Generated by eval/build_evaldata.py from eval/results_*_groq.json and eval/grades_*_groq.json.\n"
)
body = (
    "export const EVAL_DOCS = " + json.dumps(docs_js, ensure_ascii=False, indent=1) + ";\n\n"
    "export const EVAL_ROWS = " + json.dumps(rows, ensure_ascii=False, indent=1) + ";\n"
)
out_file.parent.mkdir(parents=True, exist_ok=True)
out_file.write_text(header + body, encoding="utf-8", newline="\n")

from collections import Counter

print("rows:", len(rows), "| written:", out_file)
for key, name, _, _ in DOCS:
    rr = [r for r in rows if r["doc"] == key]
    ans = [r for r in rr if r["answerable"]]
    print(key, dict(Counter(r["grade"] for r in rr)), "found", sum(r["found"] for r in ans), "/", len(ans))
